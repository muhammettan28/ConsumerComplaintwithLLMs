"""Export manuscript tables from verified, complete paired HF evaluation results."""
import json
import shutil

import pandas as pd

from sadhana_audit import ROOT, CATEGORIES

NAMES = {'gemma4': 'Gemma 4', 'qwen3': 'Qwen3', 'phi4': 'Phi-4'}


def table(caption, label, columns, heading, rows):
    return '\n'.join([
        r'\begin{table}[tb]', r'\centering', r'\footnotesize',
        r'\setlength{\tabcolsep}{3pt}', r'\caption{' + caption + '}',
        r'\label{' + label + '}', r'\begin{tabular}{' + columns + '}',
        r'\toprule', heading + r' \\', r'\midrule',
        *[r' & '.join(row) + r' \\' for row in rows],
        r'\bottomrule', r'\end{tabular}', r'\end{table}', ''])


def main():
    results = ROOT / 'results/sadhana/qlora_comparison'
    verification = json.loads((results / 'verification.json').read_text())
    assert verification['result'] == 'pass' and verification['n_full_test_predictions'] == 72000
    t = pd.read_csv(results / 'pooled_comparison.csv')
    assert len(t) == 12 and t.test_seeds_complete.all()
    order = {model: i for i, model in enumerate(NAMES)}
    t['order'] = t.model.map(order)
    t = t.sort_values(['order', 'condition', 'size'])
    comment = '% Generated by export_qlora_manuscript.py from verified saved predictions.\n'
    rows = []
    for _, r in t[t['size'].eq(500)].iterrows():
        rows.append([NAMES[r.model], 'A' if r.condition == 'balanced' else 'B',
            f'{r.base_f1_weighted:.4f}', f'{r.adapter_f1_weighted:.4f}',
            f'{100*r.delta_f1_weighted:+.2f}',
            f'[{100*r.delta_f1_weighted_ci_low:.2f}, {100*r.delta_f1_weighted_ci_high:.2f}]'])
    main_tables = comment + table(
        r'Paired HF base/QLoRA weighted F1 on 500-character tests. Each mode uses 3,000 pooled records; all adapters use 500 training and 2,000 validation records. A: balanced; B: reduced imbalance. Gains and paired 95\,\% intervals are in percentage points.',
        'tab:qlora_paired', 'llrrrr', r'Model & Condition & Base F1 & QLoRA F1 & $\Delta$ (pp) & 95\,\% CI ($\Delta$)', rows)
    rows = []
    for model in NAMES:
        r = t[t.model.eq(model) & t.condition.eq('balanced') & t['size'].eq(500)].iloc[0]
        training = json.loads((ROOT / f'checkpoints/{model}/n500/seed1/training_report.json').read_text())
        rows.append([NAMES[model], f'{r.serial_latency_s_base:.3f}', f'{r.serial_latency_s_adapter:.3f}',
            f"{training['metrics']['train_runtime']/60:.2f}", f"{training['peak_allocated_vram_gb']:.2f}"])
    main_tables += table(
        r'Local resource measurements for 500-training-record adapters. Latency: warm batch-1 mean on the same 100 balanced 500-character records per mode, including prompt preparation and generation. Training time includes validation/checkpointing and excludes initial weight loading. Memory is peak allocated CUDA memory, not total GPU utilisation.',
        'tab:qlora_resources', 'lrrrr', r'Model & Base (s) & QLoRA (s) & Train (min) & Peak (GiB)', rows)
    (ROOT / 'SPRINGER/qlora_main_tables.tex').write_text(main_tables)
    rows = []
    for _, r in t.iterrows():
        rows.append([NAMES[r.model], 'A' if r.condition == 'balanced' else 'B', str(int(r['size'])),
            f'{r.base_f1_weighted:.4f}', f'{r.adapter_f1_weighted:.4f}', f'{r.adapter_f1_macro:.4f}',
            f'{100*r.delta_f1_weighted:+.2f}',
            f'[{100*r.delta_f1_weighted_ci_low:.2f}, {100*r.delta_f1_weighted_ci_high:.2f}]',
            f'{r.mcnemar_p_holm:.2g}'])
    supplement = comment + table(
        r'Complete HF paired comparison. A: balanced; B: reduced imbalance; chars: narrative limit. Each row pools 3,000 records per mode. F1w/F1m: weighted/macro F1. Gain and CI are percentage points; $p_H$ is the exact accuracy McNemar p-value after Holm correction over twelve comparisons.',
        'tab:qlora_full', 'llrrrrrrr', r'Model & Cond. & Chars & Base F1w & QLoRA F1w & QLoRA F1m & $\Delta$ & 95\,\% CI & $p_H$', rows)
    rows = []
    for _, r in t[t['size'].eq(500)].iterrows():
        for mode in ['base', 'adapter']:
            rows.append([NAMES[r.model], 'A' if r.condition == 'balanced' else 'B', mode,
                         *[f'{r[mode+"_f1_"+c]:.4f}' for c in CATEGORIES]])
    supplement += table(
        'Pooled per-class F1 on 500-character tests. A/B denote balanced/reduced imbalance. Mortg.: mortgages and loans.',
        'tab:qlora_class', 'lllrrrrr', r'Model & Cond. & Mode & Retail & Credit rep. & Card & Mortg. & Debt', rows)
    rows = []
    for model in NAMES:
        for mode, directory in [('base', f'hf_base/{model}'), ('adapter', f'qlora/{model}_n500_s1')]:
            r = json.loads((ROOT / f'results/sadhana/{directory}/serial_benchmark_summary.json').read_text())
            rows.append([NAMES[model], mode, f'{r["mean_latency_s"]:.3f}', f'{r["median_latency_s"]:.3f}',
                         f'{r["p95_latency_s"]:.3f}', f'{100*r["batch_prediction_agreement"]:.0f}'])
    supplement += table(
        'Warm serial latency distribution on 100 fixed class-balanced records per model/mode. Agreement is with the corresponding saved full-test batched labels; full-test F1 is not replaced by the 100-record benchmark score.',
        'tab:qlora_serial', 'llrrrr', r'Model & Mode & Mean (s) & Median (s) & P95 (s) & Agreement (\%)', rows)
    (ROOT / 'SPRINGER/qlora_supplementary_tables.tex').write_text(supplement)
    revisions = [comment, r'\begin{description}']
    for model in NAMES:
        r = json.loads((ROOT / f'checkpoints/{model}/n500/seed1/training_report.json').read_text())
        revisions += [r'\item[' + NAMES[model] + '] ' + r'\path{' + r['hf_model_id'] + '}, revision ' + r'\path{' + r['hf_revision'] + '}.']
    revisions += [r'\end{description}', '']
    (ROOT / 'SPRINGER/qlora_revisions.tex').write_text('\n'.join(revisions))
    shutil.copyfile(results / 'hf_qlora_f1_comparison.pdf', ROOT / 'SPRINGER/figures/v2/hf_qlora_f1_comparison.pdf')
    report = ['# Tamamlanan HF adaptersiz / QLoRA değerlendirmesi', '',
        '8 Ekim 2026 kontrolü: üç model × iki mod × 12 dosya = **72.000 test tahmini**; ayrıca **600 seri ölçüm**. Hepsi tamamlandı ve doğrulandı.', '',
        'Eğitim: 500 dengeli kayıt, seed 1, üç epoch; ayrıca ortak 2.000 doğrulama kaydı. Model seçimi doğrulama loss’una dayanır. Üç test altkümesi üç eğitim seed’i değildir.', '',
        '| Model | Koşul | Karakter | Adaptersiz F1w | Adapterli F1w | Adapterli F1m | Artış (yüzde puan) | Artış için %95 CI |',
        '|---|---|---:|---:|---:|---:|---:|---:|']
    for _, r in t.iterrows():
        condition = 'Dengeli' if r.condition == 'balanced' else 'Azaltılmış dengesiz'
        report.append(f'| {NAMES[r.model]} | {condition} | {int(r["size"])} | {r.base_f1_weighted:.4f} | {r.adapter_f1_weighted:.4f} | {r.adapter_f1_macro:.4f} | {100*r.delta_f1_weighted:+.2f} | [{100*r.delta_f1_weighted_ci_low:.2f}, {100*r.delta_f1_weighted_ci_high:.2f}] |')
    report += ['', 'Her satır model/mod başına aynı 3.000 kaydın pooled metrikleridir. 5.000 eşleştirilmiş metin-kümesi bootstrap tekrarında iki moda aynı ağırlıklar uygulanır. Tüm artış aralıkları pozitif; 12 accuracy karşılaştırmasının tamamı Holm düzeltmesinden sonra p < 0.00142 eşiğini geçer. Bu test F1 üstünlüğü veya adapterli modeller arası sıralama testi değildir.', '',
        '| Model | Adaptersiz seri ortalama (s) | Adapterli seri ortalama (s) | Eğitim/doğrulama (dk) | Tepe allocated VRAM (GiB) |',
        '|---|---:|---:|---:|---:|']
    for model in NAMES:
        r = t[t.model.eq(model) & t.condition.eq('balanced') & t['size'].eq(500)].iloc[0]
        training = json.loads((ROOT / f'checkpoints/{model}/n500/seed1/training_report.json').read_text())
        report.append(f'| {NAMES[model]} | {r.serial_latency_s_base:.3f} | {r.serial_latency_s_adapter:.3f} | {training["metrics"]["train_runtime"]/60:.2f} | {training["peak_allocated_vram_gb"]:.2f} |')
    report += ['', 'Seri benchmark: ilk dengeli 500-karakter testinden sınıf başına ilk 20 kayıt, aynı 100 örnek/model/mod, warmup sonrası batch 1. Süre prompt/tokenizasyon ve CUDA generation içerir; çıktı decoding, yükleme ve ağ sunucusu gideri içermez. Fine-tuning tüm modelleri hızlandırmaz: Gemma/Qwen süreleri artar, Phi’nin ölçülen ortalaması azalır.', '',
        '36.000 adapterli test çıktısında geçersiz cevap yoktur. Adaptersiz Gemma’da 2, Qwen’de 0, Phi’de 21 geçersiz cevap vardır; bunlar hata sayılır. Seri/batch etiket uyumu Gemma için %100/%99, Qwen için %98/%100 ve Phi için %100/%100 (base/adapter). Üç farklı etiketin kaynak hash ve giriş token sayısı aynıdır; hesaplama nedeni izole edilmedi. F1 tam batched tahminlerden hesaplanır.', '',
        'Doğrulama: altı completion manifesti/tahmin SHA256 değeri; train/validation/test/adapter hash’leri; kaynak/etiket/indeks eşleşmeleri; ham cevapların yeniden ayrıştırılması; eşit çiftli batch boyutları; pooled F1/accuracy; seri seçim/süre/uyum. Sonuç: geçti.', '',
        '500 eğitim etiketi + ortak validation ile üç adapter matched HF tabanını iyileştirir. 20.000 eğitim etiketli SVM (F1 0.8291) ve DistilBERT (üç eğitim seed’i ortalaması 0.8244) farklı bütçeye aittir. Tek adapter eğitim seed’i, test CI’larının eğitim belirsizliğini ölçmemesi ve yalnızca 100 örneklik seri benchmark temel sınırlardır. Eski Ollama GGUF sonuçları adaptasyon tabanı olarak kullanılmadı.', '',
        'Makaleye yöntem, ana/ek tablolar, şekil, başlık/özet/katkılar, tartışma ve sonuç olarak işlendi. Dergi biçimi ve son sayfa kısaltması henüz yapılmadı.', '',
        '- [Pooled metrikler ve güven aralıkları](pooled_comparison.csv)',
        '- [Altküme ve sınıf metrikleri](per_test_comparison.csv)',
        '- [Karşılaştırma şekli](hf_qlora_f1_comparison.pdf)',
        '- [Doğrulama kaydı](verification.json)',
        '- [Seri/batch etiket farkları](serial_batch_disagreements.csv)',
        '- [Yöntem kaydı](comparison_method.json)', '']
    (results / 'report.md').write_text('\n'.join(report))
    print('Exported main, supplementary and revision tables from all 12 verified groups.')


if __name__ == '__main__':
    main()
